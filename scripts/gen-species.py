#!/usr/bin/env python3
"""Generate packages/data/src/species.generated.ts from the pret decompilation.

Gen 3 stores an *internal* species index that is NOT the National Dex number,
and the relationship is not a fixed offset. It is tempting to assume Gen 3
species are simply shifted by 25 (SPECIES_TREECKO 277 -> national 252 works),
but the internal ordering is not National Dex ordering:

    SPECIES_NINCADA  = 301 (internal)   ->  national 290
    301 - 25 = 276                      ->  WRONG

So the mapping must be a real table. It is built by joining two authoritative
lists from pokeemerald on the species name:

    include/constants/species.h  ->  SPECIES_X = internal index
    include/constants/pokedex.h  ->  NATIONAL_DEX_X enum position = national no.

Run with: pnpm gen:species
"""

from __future__ import annotations

import re
import urllib.request
from pathlib import Path

SPECIES_URL = "https://raw.githubusercontent.com/pret/pokeemerald/master/include/constants/species.h"
POKEDEX_URL = "https://raw.githubusercontent.com/pret/pokeemerald/master/include/constants/pokedex.h"

OUT = Path(__file__).resolve().parent.parent / "packages/data/src/species.generated.ts"


def fetch(url: str) -> str:
    with urllib.request.urlopen(url) as response:
        return response.read().decode("utf-8")


def internal_indices(source: str) -> dict[str, int]:
    """SPECIES_BULBASAUR -> 1 (internal index)."""
    return {
        name: int(value)
        for name, value in re.findall(r"#define SPECIES_(\w+)\s+(\d+)", source)
    }


def national_numbers(source: str) -> dict[str, int]:
    """NATIONAL_DEX_BULBASAUR -> 1, from enum position.

    The enum is declared in National Dex order starting at NATIONAL_DEX_NONE=0,
    so ordinal position is the dex number. Two traps:

    - The HOENN_DEX enum below reuses the same species names in a different
      order, so everything from there on must be discarded.
    - After the enum, trailing #defines reference names again (e.g.
      NATIONAL_DEX_DEOXYS). Those repeats sit at much higher positions, so only
      the FIRST occurrence of each name is the real dex number.
    """
    head = source.split("HOENN_DEX_")[0]
    numbers: dict[str, int] = {}
    for index, name in enumerate(re.findall(r"NATIONAL_DEX_(\w+)", head)):
        if name == "COUNT":
            break
        numbers.setdefault(name, index)
    return numbers


def main() -> None:
    internal = internal_indices(fetch(SPECIES_URL))
    national = national_numbers(fetch(POKEDEX_URL))

    # Internal 252-276 are the OLD_UNOWN_* placeholder slots. They occupy
    # positions past Deoxys in the national enum, so anything above 386 is not
    # a real species and must not be mapped.
    mapping: dict[int, int] = {}
    for name, index in internal.items():
        dex = national.get(name)
        if dex is not None and 1 <= dex <= 386:
            mapping[index] = dex

    shifted = sum(
        1 for i, d in mapping.items() if i > 251 and i - d != 25
    )

    lines = [
        "// GENERATED by scripts/gen-species.py -- do not edit by hand.",
        "// Source: pret/pokeemerald (constants/species.h + constants/pokedex.h).",
        "//",
        "// Gen 3 internal species index -> National Dex number.",
        "// NOT a fixed offset: internal order is not National Dex order.",
        f"// {shifted} Gen 3 species do not follow the naive -25 shift.",
        "",
        "export const INTERNAL_TO_NATIONAL: Readonly<Record<number, number>> = {",
        *(f"  {index}: {mapping[index]}," for index in sorted(mapping)),
        "};",
        "",
    ]

    OUT.write_text("\n".join(lines))
    print(f"{len(mapping)} species mapped; {shifted} break the -25 assumption")
    for probe in ("BULBASAUR", "TREECKO", "NINCADA", "SHEDINJA", "DEOXYS"):
        print(f"  {probe}: internal {internal[probe]} -> national {national[probe]}")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
