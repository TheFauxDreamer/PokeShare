#!/usr/bin/env python3
"""Generate packages/data/src/families.generated.ts from the pret decompilation.

The dupes and species clauses work on *evolutionary families*: catching a
Zigzagoon when you already have a Linoone is still a dupe. This turns
pokeemerald's evolution table into a National Dex -> family-id map, where the
family id is the lowest dex number in the family.

IMPORTANT: this is the **vanilla** table. A UPR-ZX randomised ROM rewrites
evolutions, so these families are wrong for a randomised run — which is why the
run carries a `randomised` flag that disables family grouping. The correct fix
for randomised ROMs is to read gEvolutionTable out of the ROM file, which needs
a per-version address nobody has published; see PLAN.md.

Run with: pnpm gen:families
"""

from __future__ import annotations  # `int | None` on Python 3.9

import re
import urllib.request
from pathlib import Path

POKEDEX_URL = "https://raw.githubusercontent.com/pret/pokeemerald/master/include/constants/pokedex.h"
EVOLUTION_URL = "https://raw.githubusercontent.com/pret/pokeemerald/master/src/data/pokemon/evolution.h"

OUT = Path(__file__).resolve().parent.parent / "packages/data/src/families.generated.ts"

NATIONAL_DEX_MAX = 386


def fetch(url: str) -> str:
    with urllib.request.urlopen(url) as response:
        return response.read().decode("utf-8")


def species_indices(source: str) -> dict[str, int]:
    """SPECIES_BULBASAUR -> National Dex number.

    Resolved straight to National Dex rather than via the internal index: the
    internal ordering is not National Dex ordering and there is no fixed offset
    between them (see scripts/gen-species.py). Keyed by the `SPECIES_` prefix so
    evolution.h names match directly.
    """
    head = source.split("HOENN_DEX_")[0]
    numbers: dict[str, int] = {}
    for index, name in enumerate(re.findall(r"NATIONAL_DEX_(\w+)", head)):
        if name == "COUNT":
            break
        numbers.setdefault(name, index)
    return {
        f"SPECIES_{name}": dex
        for name, dex in numbers.items()
        if 1 <= dex <= NATIONAL_DEX_MAX
    }


def evolution_edges(source: str, indices: dict[str, int]) -> list[tuple[int, int]]:
    """Extract (from_national, to_national) pairs, skipping unmapped species.

    Split on the `[SPECIES_X] =` anchors rather than trying to match balanced
    braces: a species with branching evolutions (Gloom, Eevee) spans several
    lines and several inner `{...}` entries, and a non-greedy brace match would
    silently capture only the first of them.
    """
    edges: list[tuple[int, int]] = []
    parts = re.split(r"\[(SPECIES_\w+)\]\s*=\s*", source)

    # parts[0] is the preamble; thereafter name/body alternate.
    for origin_name, body in zip(parts[1::2], parts[2::2]):
        origin = indices.get(origin_name)
        if origin is None:
            continue
        # The target is the third member of each {method, param, target} entry.
        for target_name in re.findall(r",\s*(SPECIES_\w+)\s*\}", body):
            target = indices.get(target_name)
            if target is not None:
                edges.append((origin, target))
    return edges


def build_families(edges: list[tuple[int, int]]) -> dict[int, int]:
    """Union-find over evolution edges; representative is the lowest dex."""
    parent: dict[int, int] = {}

    def find(x: int) -> int:
        parent.setdefault(x, x)
        while parent[x] != x:
            parent[x] = parent[parent[x]]
            x = parent[x]
        return x

    def union(a: int, b: int) -> None:
        ra, rb = find(a), find(b)
        if ra != rb:
            # Point at the lower dex so the representative is the base form.
            low, high = (ra, rb) if ra < rb else (rb, ra)
            parent[high] = low

    for a, b in edges:
        union(a, b)

    return {dex: find(dex) for dex in sorted(parent) if find(dex) != dex}


def main() -> None:
    indices = species_indices(fetch(POKEDEX_URL))
    edges = evolution_edges(fetch(EVOLUTION_URL), indices)
    families = build_families(edges)

    lines = [
        "// GENERATED by scripts/gen-families.py -- do not edit by hand.",
        "// Source: pret/pokeemerald (species.h + evolution.h), VANILLA evolutions.",
        "//",
        "// Maps a National Dex number to its family id (the lowest dex in the",
        "// family). Species absent from this map are their own family.",
        "//",
        "// Wrong for UPR-ZX randomised ROMs, which rewrite evolutions -- runs",
        "// flagged as randomised disable family grouping instead.",
        "",
        "export const EVOLUTION_FAMILIES: Readonly<Record<number, number>> = {",
        *(f"  {dex}: {root}," for dex, root in families.items()),
        "};",
        "",
    ]

    OUT.write_text("\n".join(lines))
    print(f"{len(edges)} evolution edges -> {len(families)} non-base species")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
