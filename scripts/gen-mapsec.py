#!/usr/bin/env python3
"""Generate packages/data/src/mapsec.generated.ts from the pret decompilations.

A Gen 3 map header carries a `regionMapSectionId` (MAPSEC) byte at offset 0x14.
That byte is what gives us "Route 103" / "Petalburg Woods" — exactly the
granularity Soul Link pairs on. The numeric value is the index of the entry in
each game's region_map_sections.json, so ordering is load-bearing.

The three tables are NOT interchangeable: Ruby/Sapphire, Emerald and FRLG each
number their sections differently. Run with: pnpm gen:mapsec
"""

import json
import urllib.request
from pathlib import Path

SOURCES = {
    "RS": "https://raw.githubusercontent.com/pret/pokeruby/master/src/data/region_map/region_map_sections.json",
    "EMERALD": "https://raw.githubusercontent.com/pret/pokeemerald/master/src/data/region_map/region_map_sections.json",
    "FRLG": "https://raw.githubusercontent.com/pret/pokefirered/master/src/data/region_map/region_map_sections.json",
}

OUT = Path(__file__).resolve().parent.parent / "packages/data/src/mapsec.generated.ts"


def display_name(section: dict) -> str:
    """MAPSEC_ROUTE_103 -> "Route 103".

    Derived from `id` rather than `name` because pokefirered's JSON omits
    `name` entirely, and deriving keeps all three tables consistent.
    """
    words = section["id"].removeprefix("MAPSEC_").split("_")
    return " ".join(w.capitalize() if w.isalpha() else w for w in words)


def fetch(url: str) -> list[dict]:
    with urllib.request.urlopen(url) as r:
        return json.load(r)["map_sections"]


def emit(label: str, sections: list[dict]) -> str:
    lines = [f"export const {label}_MAPSEC: Readonly<Record<number, string>> = {{"]
    for index, section in enumerate(sections):
        lines.append(f"  {index}: {json.dumps(display_name(section))},")
    lines.append("};\n")
    return "\n".join(lines)


def main() -> None:
    blocks = [
        "// GENERATED by scripts/gen-mapsec.py -- do not edit by hand.",
        "// Source: pret/pokeruby, pret/pokeemerald, pret/pokefirered (region_map_sections.json).",
        "// Index == the MAPSEC value found at gMapHeader + 0x14.\n",
    ]
    for label, url in SOURCES.items():
        sections = fetch(url)
        blocks.append(emit(label, sections))
        print(f"{label}: {len(sections)} sections")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(blocks))
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
